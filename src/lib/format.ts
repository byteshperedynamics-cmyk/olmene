import type { ReportData } from "./report-types";

export function scoreTone(v: number): string {
  return v >= 75 ? "score-good" : v >= 50 ? "score-mid" : "score-bad";
}

export function scoreLabel(v: number): string {
  return v >= 75 ? "Strong" : v >= 50 ? "Developing" : "Needs work";
}

export function severityClass(sev: string): string {
  switch (sev) {
    case "critical":
      return "sev-critical";
    case "high":
      return "sev-high";
    case "medium":
      return "sev-medium";
    default:
      return "sev-low";
  }
}

export function statusIconClass(status: string): string {
  switch (status) {
    case "pass":
      return "score-good";
    case "warn":
      return "score-mid";
    default:
      return "score-bad";
  }
}

export function fmtDate(iso: string | null | undefined): string {
  if (!iso) return "";
  return new Date(iso).toLocaleDateString(undefined, { year: "numeric", month: "short", day: "numeric" });
}

export function fmtDateTime(iso: string | null | undefined): string {
  if (!iso) return "";
  return new Date(iso).toLocaleString(undefined, {
    month: "short",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
}

// ── Markdown export ─────────────────────────────────────────────────────

function mdEscape(s: string): string {
  return s.replace(/\n{3,}/g, "\n\n").trim();
}

export function reportToMarkdown(r: ReportData, sample = false): string {
  const L: string[] = [];
  const s = r.executiveSummary.scores;
  const src = (ids: string[] | undefined) =>
    ids?.length ? ` ${ids.map((i) => `[${i}]`).join(" ")}` : "";

  L.push(`# ${r.product.name} — Marketing Report`);
  L.push("");
  if (sample) {
    L.push("> **FICTIONAL EXAMPLE — NOT A REAL AUDIT.** All numbers and source references in this sample are invented to demonstrate the report format.");
    L.push("");
  }
  L.push(`> Generated by Olmene · ${sample ? "Fictional site" : r.meta.siteUrl} · ${fmtDate(r.meta.generatedAt)} · Language: ${r.meta.language}`);
  L.push("");
  L.push("## Executive summary");
  L.push("");
  L.push(r.executiveSummary.headline);
  L.push("");
  L.push(`**Overall score: ${s.overall}/100** (Messaging ${s.messaging} · Positioning ${s.positioning} · Conversion ${s.conversion} · SEO ${s.seo} · Trust ${s.trust})`);
  L.push("");
  L.push("### Top findings");
  r.executiveSummary.topFindings.forEach((f) => L.push(`- ${f}`));
  L.push("");
  L.push(`### Biggest opportunity`);
  L.push(r.executiveSummary.biggestOpportunity);
  L.push("");

  L.push("## Your product");
  L.push("");
  L.push(`**${r.product.name}** — ${r.product.category}`);
  L.push(r.product.oneLiner);
  L.push("");
  L.push(`**Pricing model:** ${r.product.pricingModel}`);
  L.push("");
  L.push("**Offerings:**");
  r.product.offerings.forEach((o) => L.push(`- ${o}`));
  L.push("");
  L.push("**Target customers:**");
  r.product.targetCustomers.forEach((t) => L.push(`- ${t}`));
  L.push("");

  L.push("## Market");
  L.push("");
  L.push(r.market.definition);
  L.push("");
  L.push(`**Market size:** ${r.market.size.value} (confidence: ${r.market.size.confidence})${src(r.market.size.sourceIds)}`);
  L.push("");
  L.push("### Trends");
  r.market.trends.forEach((t) => L.push(`- **${t.trend}**${src(t.sourceIds)} — ${t.implication}`));
  L.push("");
  L.push("### Segments");
  r.market.segments.forEach((seg) =>
    L.push(`- **${seg.name}** (fit ${seg.fitScore}/100) — ${seg.why} Reach via: ${seg.howToReach}`),
  );
  L.push("");
  L.push(r.market.potentialAssessment);
  L.push("");

  L.push("## Competitors");
  L.push("");
  r.competitors.forEach((c) => {
    L.push(`### ${c.name}${src(c.sourceIds)}`);
    L.push(`- **Positioning:** ${c.positioning}`);
    L.push(`- **Pricing:** ${c.pricing ?? "n/a"}`);
    L.push(`- **Strengths:** ${c.strengths.join("; ")}`);
    L.push(`- **Weaknesses:** ${c.weaknesses.join("; ")}`);
    L.push(`- **Gap to exploit:** ${c.gapToExploit}`);
    L.push(`- **Threat:** ${c.threat}`);
    L.push("");
  });

  L.push("## Site audit");
  L.push("");
  const auditSection = (title: string, findings: { title: string; severity: string; evidence: string; recommendation: string }[]) => {
    L.push(`### ${title}`);
    if (!findings.length) L.push("_No findings._");
    findings.forEach((f) => {
      L.push(`- **[${f.severity.toUpperCase()}] ${f.title}**`);
      L.push(`  - Evidence: ${f.evidence}`);
      L.push(`  - Recommendation: ${f.recommendation}`);
    });
    L.push("");
  };
  auditSection("Messaging", r.audit.messaging);
  auditSection("Conversion", r.audit.conversion);
  auditSection("SEO content findings", r.audit.seo.findings);
  auditSection("Trust", r.audit.trust);
  auditSection("Pricing presentation", r.audit.pricingPresentation);

  L.push("### SEO checklist (computed from your HTML)");
  L.push("");
  L.push("| Check | Status | Detail |");
  L.push("| --- | --- | --- |");
  r.audit.seo.checklist.forEach((c) => L.push(`| ${c.check} | ${c.status.toUpperCase()} | ${c.detail} |`));
  L.push("");

  L.push("## Strategy");
  L.push("");
  L.push(`**Positioning:** ${r.strategy.positioning.statement}`);
  L.push("");
  L.push("**Differentiators:**");
  r.strategy.positioning.differentiators.forEach((d) => L.push(`- ${d}`));
  L.push("");
  L.push("### Ideal customer profiles");
  r.strategy.icp.forEach((i) => {
    L.push(`- **${i.persona}** — pains: ${i.painPoints.join("; ")}; triggers: ${i.triggers.join("; ")}${i.objections?.length ? `; objections: ${i.objections.join("; ")}` : ""}`);
  });
  L.push("");
  if (r.strategy.channels?.length) {
    L.push("### Channels");
    r.strategy.channels
      .slice()
      .sort((a, b) => a.priority - b.priority)
      .forEach((c) => {
        L.push(`- **${c.channel}** — ${c.rationale}`);
        c.firstSteps?.forEach((f) => L.push(`  - First step: ${f}`));
      });
    L.push("");
  }
  if (r.strategy.offerAndPricingIdeas?.length) {
    L.push("### Offer & pricing ideas");
    r.strategy.offerAndPricingIdeas.forEach((o) => L.push(`- ${o}`));
    L.push("");
  }
  if (r.strategy.contentThemes?.length) {
    L.push("### Content themes");
    r.strategy.contentThemes.forEach((t) => L.push(`- ${t}`));
    L.push("");
  }

  L.push("## Roadmap");
  L.push("");
  const roadmapSection = (title: string, items: ReportData["roadmap"]["quickWins"]) => {
    L.push(`### ${title}`);
    items.forEach((a, i) => {
      L.push(`${i + 1}. **${a.title}**`);
      L.push(`   - Why: ${a.why}`);
      L.push(`   - How: ${a.how}`);
      L.push(`   - Effort: ${a.effort} · Impact: ${a.impact} · KPI: ${a.kpi}${realDependency(a.dependsOn) ? ` · Depends on: ${a.dependsOn}` : ""}`);
    });
    L.push("");
  };
  roadmapSection("Quick wins — this week (≤ 7 days)", r.roadmap.quickWins ?? []);
  roadmapSection("30 days", r.roadmap.days30 ?? []);
  roadmapSection("60 days", r.roadmap.days60 ?? []);
  roadmapSection("90 days", r.roadmap.days90 ?? []);

  L.push("## Risks");
  L.push("");
  r.risks.forEach((k) => L.push(`- **${k.risk}** — mitigation: ${k.mitigation}`));
  L.push("");

  L.push("## Sources");
  L.push("");
  if (sample) L.push("_These are placeholder references in a fictional example; source URLs are omitted._");
  r.sources.forEach((x) => L.push(sample ? `- [${x.id}] ${x.title} (fictional placeholder)` : `- [${x.id}] ${x.title} — ${x.url}`));
  L.push("");

  L.push("## Assumptions");
  L.push("");
  r.assumptions.forEach((a) => L.push(`- ${a}`));
  L.push("");
  L.push(sample ? "_Fictional example only. This is not research or advice about a real business._" : "_This report is AI-generated from public web data. Verify facts and figures before acting on them._");
  return mdEscape(L.join("\n"));
}

export function buildActionPlan(r: ReportData, sample = false): string {
  const L: string[] = [];
  if (sample) {
    L.push("FICTIONAL EXAMPLE — NOT A REAL ACTION PLAN. The business and recommendations below are invented to demonstrate the format.");
    L.push("");
  }
  L.push(`ACTION PLAN — ${r.product.name} (generated ${fmtDate(r.meta.generatedAt)})`);
  L.push("");
  const section = (title: string, items: ReportData["roadmap"]["quickWins"]) => {
    L.push(`${title.toUpperCase()}`);
    items.forEach((a, i) =>
      L.push(`${i + 1}. [${a.effort} effort / ${a.impact} impact] ${a.title} — KPI: ${a.kpi}${realDependency(a.dependsOn) ? ` (after: ${a.dependsOn})` : ""}`),
    );
    L.push("");
  };
  section("This week (≤ 7 days)", r.roadmap.quickWins ?? []);
  section("30 days", r.roadmap.days30 ?? []);
  section("60 days", r.roadmap.days60 ?? []);
  section("90 days", r.roadmap.days90 ?? []);
  return L.join("\n").trim();
}

/** "None", "N/A" and friends are what models write for "no dependency". */
export function realDependency(v: string | null | undefined): boolean {
  return !!v && !/^(?:none|n\/?a|null|-|—|nothing|no dependenc(?:y|ies)|not applicable)\.?$/i.test(v.trim());
}
