/**
 * Minimal, conservative editing of Next.js App Router source files.
 *
 * The TypeScript compiler is far too large for the Worker bundle, so this is
 * a small scanner that understands strings, comments and template literals
 * well enough to find and edit ONE thing safely: a plain object literal
 * assigned to `export const metadata`. Anything unusual — spreads, computed
 * keys, generateMetadata, non-literal values we would have to rewrite —
 * returns a skip reason instead of an edit ("skip rather than guess").
 * Every successful edit is re-parsed before it is returned.
 */

export type JsEdit = { ok: true; content: string } | { ok: false; reason: string };

/** Mask of code positions: true where the char is real code (not string/comment). */
export function codeMask(src: string): boolean[] {
  const mask = new Array<boolean>(src.length).fill(true);
  // stack of template-literal brace depths for nested ${ … }
  const tmpl: number[] = [];
  let braceDepth = 0;
  let i = 0;
  const mark = (from: number, to: number) => {
    for (let k = from; k < to && k < src.length; k++) mask[k] = false;
  };
  while (i < src.length) {
    const c = src[i];
    const n = src[i + 1];
    if (c === "/" && n === "/") {
      const end = src.indexOf("\n", i);
      const stop = end < 0 ? src.length : end;
      mark(i, stop);
      i = stop;
      continue;
    }
    if (c === "/" && n === "*") {
      const end = src.indexOf("*/", i + 2);
      const stop = end < 0 ? src.length : end + 2;
      mark(i, stop);
      i = stop;
      continue;
    }
    if (c === '"' || c === "'") {
      let j = i + 1;
      while (j < src.length && src[j] !== c && src[j] !== "\n") j += src[j] === "\\" ? 2 : 1;
      mark(i, j + 1);
      i = j + 1;
      continue;
    }
    if (c === "`" || (c === "}" && tmpl.length > 0 && tmpl[tmpl.length - 1] === braceDepth)) {
      // start of a template literal, or the end of a ${…} that resumes one
      if (c === "}") tmpl.pop();
      let j = i + 1;
      while (j < src.length) {
        if (src[j] === "\\") {
          j += 2;
          continue;
        }
        if (src[j] === "`") break;
        if (src[j] === "$" && src[j + 1] === "{") break;
        j++;
      }
      mark(i, Math.min(j + 1, src.length));
      if (src[j] === "$") {
        mark(j, j + 2);
        tmpl.push(braceDepth);
        i = j + 2;
      } else {
        i = j + 1;
      }
      continue;
    }
    if (c === "{") braceDepth++;
    else if (c === "}") braceDepth--;
    i++;
  }
  return mask;
}

/** Index of the brace matching the `{` at `open` (code positions only), or -1. */
export function matchBrace(src: string, mask: boolean[], open: number): number {
  let depth = 0;
  for (let k = open; k < src.length; k++) {
    if (!mask[k]) continue;
    if (src[k] === "{") depth++;
    else if (src[k] === "}") {
      depth--;
      if (depth === 0) return k;
    }
  }
  return -1;
}

/** First regex match whose start lies in code. */
function findInCode(src: string, mask: boolean[], re: RegExp): RegExpExecArray | null {
  const g = new RegExp(re.source, re.flags.includes("g") ? re.flags : re.flags + "g");
  let m: RegExpExecArray | null;
  while ((m = g.exec(src)) !== null) {
    if (mask[m.index]) return m;
  }
  return null;
}

function countInCode(src: string, mask: boolean[], re: RegExp): number {
  const g = new RegExp(re.source, re.flags.includes("g") ? re.flags : re.flags + "g");
  let m: RegExpExecArray | null;
  let n = 0;
  while ((m = g.exec(src)) !== null) if (mask[m.index]) n++;
  return n;
}

export interface MetaProp {
  key: string;
  /** whole "key: value" segment, trimmed */
  segStart: number;
  segEnd: number;
  valueStart: number;
  valueEnd: number;
  /** value is a single plain string literal ('…' or "…") */
  stringLiteral: boolean;
}

export interface MetadataObject {
  open: number;
  close: number;
  props: MetaProp[];
  multiline: boolean;
  /** indentation for new properties */
  indent: string;
}

/** Locate `export const metadata = { … }` and list its top-level properties. */
export function findMetadataObject(src: string): MetadataObject | { reason: string } {
  const mask = codeMask(src);
  if (findInCode(src, mask, /\bexport\s+(async\s+)?function\s+generateMetadata\b|\bexport\s+const\s+generateMetadata\b/)) {
    return { reason: "Metadata is generated by generateMetadata() — not editing generated values." };
  }
  if (countInCode(src, mask, /\bexport\s+const\s+metadata\b/) > 1) {
    return { reason: "More than one metadata export found." };
  }
  const decl = findInCode(src, mask, /\bexport\s+const\s+metadata\s*(?::\s*[A-Za-z_$][\w$.]*\s*)?=\s*/);
  if (!decl) return { reason: "No `export const metadata` object in the root layout." };
  const open = decl.index + decl[0].length;
  if (src[open] !== "{") {
    return { reason: "`metadata` is not a plain object literal (it is built from another value)." };
  }
  const close = matchBrace(src, mask, open);
  if (close < 0) return { reason: "Could not find the end of the metadata object." };

  // split top-level segments by commas at depth 0 (relative)
  const props: MetaProp[] = [];
  let depth = 0;
  let segStart = open + 1;
  const flush = (end: number): string | null => {
    const raw = src.slice(segStart, end);
    const lead = raw.length - raw.trimStart().length;
    const text = raw.trim();
    if (!text) return null;
    const s = segStart + lead;
    const e = s + text.length;
    if (text.startsWith("...")) return "Metadata spreads another object — not editing it.";
    const km = text.match(/^(?:([A-Za-z_$][\w$]*)|"([^"]+)"|'([^']+)')\s*:\s*/);
    if (!km) {
      if (/^\[/.test(text)) return "Metadata uses computed keys — not editing it.";
      if (/^[A-Za-z_$][\w$]*$/.test(text)) {
        props.push({ key: text, segStart: s, segEnd: e, valueStart: s, valueEnd: e, stringLiteral: false });
        return null;
      }
      return "Metadata object has a property this editor does not understand.";
    }
    const key = km[1] ?? km[2] ?? km[3];
    const vs = s + km[0].length;
    const value = src.slice(vs, e);
    const stringLiteral = /^(?:"(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*')$/.test(value);
    props.push({ key, segStart: s, segEnd: e, valueStart: vs, valueEnd: e, stringLiteral });
    return null;
  };
  for (let k = open + 1; k < close; k++) {
    if (!mask[k]) continue;
    const c = src[k];
    if (c === "{" || c === "[" || c === "(") depth++;
    else if (c === "}" || c === "]" || c === ")") depth--;
    else if (c === "," && depth === 0) {
      const err = flush(k);
      if (err) return { reason: err };
      segStart = k + 1;
    }
  }
  const err = flush(close);
  if (err) return { reason: err };

  const body = src.slice(open + 1, close);
  const multiline = body.includes("\n");
  let indent = "  ";
  if (multiline && props.length) {
    const lineStart = src.lastIndexOf("\n", props[0].segStart) + 1;
    indent = src.slice(lineStart, props[0].segStart);
    if (!/^[ \t]*$/.test(indent)) indent = "  ";
  } else {
    const lineStart = src.lastIndexOf("\n", decl.index) + 1;
    const base = src.slice(lineStart, decl.index).match(/^[ \t]*/)?.[0] ?? "";
    indent = base + "  ";
  }
  return { open, close, props, multiline, indent };
}

const str = (v: string) => JSON.stringify(v);

/** Re-parse after an edit; returns the edit only if the object is still well-formed. */
function verified(next: string, key: string): JsEdit {
  const again = findMetadataObject(next);
  if ("reason" in again) return { ok: false, reason: `Edit could not be verified: ${again.reason}` };
  if (!again.props.some((p) => p.key === key)) return { ok: false, reason: "Edit could not be verified." };
  return { ok: true, content: next };
}

function insertProp(src: string, obj: MetadataObject, code: string): string {
  if (obj.multiline || obj.props.length === 0) {
    // after the opening brace, on its own line
    const closeLineStart = src.lastIndexOf("\n", obj.close) + 1;
    const closeIndent = src.slice(closeLineStart, obj.close);
    if (obj.props.length === 0) {
      const base = /^[ \t]*$/.test(closeIndent) ? closeIndent : "";
      const inner = obj.indent;
      return `${src.slice(0, obj.open + 1)}\n${inner}${code},\n${base}${src.slice(obj.close)}`;
    }
    return `${src.slice(0, obj.open + 1)}\n${obj.indent}${code},${src.slice(obj.open + 1)}`;
  }
  // single-line object: { title: "x" } → { description: "…", title: "x" }
  return `${src.slice(0, obj.open + 1)} ${code},${src.slice(obj.open + 1)}`;
}

/** Set a top-level string property (insert, or replace a plain string literal). */
export function setMetadataString(src: string, key: string, value: string): JsEdit {
  const obj = findMetadataObject(src);
  if ("reason" in obj) return { ok: false, reason: obj.reason };
  const prop = obj.props.find((p) => p.key === key);
  if (prop) {
    if (!prop.stringLiteral) {
      return { ok: false, reason: `\`${key}\` is set from an expression or object — not rewriting it.` };
    }
    const next = src.slice(0, prop.valueStart) + str(value) + src.slice(prop.valueEnd);
    return verified(next, key);
  }
  return verified(insertProp(src, obj, `${key}: ${str(value)}`), key);
}

/** Add `alternates: { canonical: url }` only when `alternates` is absent. */
export function addMetadataCanonical(src: string, url: string): JsEdit {
  const obj = findMetadataObject(src);
  if ("reason" in obj) return { ok: false, reason: obj.reason };
  if (obj.props.some((p) => p.key === "alternates")) {
    return { ok: false, reason: "`alternates` is already defined — not editing nested metadata." };
  }
  return verified(insertProp(src, obj, `alternates: { canonical: ${str(url)} }`), "alternates");
}

/**
 * Add `import { Name } from "spec";` after the last top-level import and
 * render `<Name />` as the first child of the single <body> element.
 */
export function addBodyComponent(src: string, name: string, spec: string): JsEdit {
  const mask = codeMask(src);
  if (new RegExp(`\\b${name}\\b`).test(src)) return { ok: false, reason: `${name} is already used in this file.` };
  if (countInCode(src, mask, /<body\b/) !== 1) return { ok: false, reason: "Root layout does not have exactly one <body> element." };
  const bodyAt = findInCode(src, mask, /<body\b/)!.index;
  // find the end of the opening tag, skipping {…} attribute expressions
  let k = bodyAt + 5;
  let depth = 0;
  for (; k < src.length; k++) {
    if (!mask[k]) continue;
    if (src[k] === "{") depth++;
    else if (src[k] === "}") depth--;
    else if (src[k] === ">" && depth === 0) break;
  }
  if (k >= src.length || src[k - 1] === "/") return { ok: false, reason: "Could not find the <body> opening tag safely." };
  const lineStart = src.lastIndexOf("\n", bodyAt) + 1;
  const bodyIndent = src.slice(lineStart, bodyAt).match(/^[ \t]*/)?.[0] ?? "";
  const childIndent = bodyIndent + "  ";
  let next = `${src.slice(0, k + 1)}\n${childIndent}<${name} />${src.slice(k + 1)}`;

  // import after the last top-level import statement (or after directives)
  const importLine = `import { ${name} } from ${str(spec)};`;
  const re = /^import\s+(?:[\s\S]*?\sfrom\s+)?["'][^"'\n]+["'];?[^\S\n]*$/gm;
  let last: RegExpExecArray | null = null;
  let m: RegExpExecArray | null;
  const nmask = codeMask(next);
  while ((m = re.exec(next)) !== null) if (nmask[m.index]) last = m;
  if (last) {
    const at = last.index + last[0].length;
    next = `${next.slice(0, at)}\n${importLine}${next.slice(at)}`;
  } else {
    const directive = next.match(/^\s*(["'])use (client|server)\1;?[^\S\n]*\n/);
    const at = directive ? directive[0].length : 0;
    next = `${next.slice(0, at)}${importLine}\n${next.slice(at)}`;
  }
  // sanity: braces still balance in code
  const vm = codeMask(next);
  let bal = 0;
  for (let i = 0; i < next.length; i++) {
    if (!vm[i]) continue;
    if (next[i] === "{") bal++;
    else if (next[i] === "}") bal--;
    if (bal < 0) break;
  }
  if (bal !== 0) return { ok: false, reason: "Edit could not be verified (unbalanced braces)." };
  return { ok: true, content: next };
}
